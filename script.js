// Intersection Observer for Active Nav Link Highlight on Scroll
function setupActiveLinkObserver() {
    const sections = document.querySelectorAll('section');
    if (!sections || !sections.length) return; // Guard for subpages without standard sections
    const options = {
        root: null,
        threshold: 0.3,
        rootMargin: "-80px 0px 0px 0px" // Account for header height
    };
    
    const observer = new IntersectionObserver((entries) => {
        entries.forEach(entry => {
            if (entry.isIntersecting) {
                const id = entry.target.getAttribute('id');
                navLinks.forEach(link => {
                    link.classList.remove('active');
                    if (link.getAttribute('href') === `#${id}`) {
                        link.classList.add('active');
                    }
                });
            }
        });
    }, options);
    
    sections.forEach(section => {
        observer.observe(section);
    });
}

