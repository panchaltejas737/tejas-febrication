// Lightbox for gallery images
function initGalleryLightbox() {
    const galleryItems = document.querySelectorAll('.gallery-item');
    if (!galleryItems.length) return;

    // Create Lightbox DOM structure if it doesn't exist
    let lightbox = document.getElementById('galleryLightbox');
    if (!lightbox) {
        lightbox = document.createElement('div');
        lightbox.id = 'galleryLightbox';
        lightbox.className = 'lightbox';
        lightbox.innerHTML = `
            <div class="lightbox-content">
                <button class="lightbox-close" id="lightboxClose">&times;</button>
                <button class="lightbox-nav lightbox-prev" id="lightboxPrev">&#10094;</button>
                <img class="lightbox-img" id="lightboxImg" src="" alt="">
                <div class="lightbox-caption" id="lightboxCaption"></div>
                <button class="lightbox-nav lightbox-next" id="lightboxNext">&#10095;</button>
            </div>
        `;
        document.body.appendChild(lightbox);
    }

    const lightboxImg = document.getElementById('lightboxImg');
    const lightboxCaption = document.getElementById('lightboxCaption');
    const lightboxClose = document.getElementById('lightboxClose');
    const lightboxPrev = document.getElementById('lightboxPrev');
    const lightboxNext = document.getElementById('lightboxNext');

    let currentIndex = 0;
    const itemsArray = Array.from(galleryItems).filter(item => !item.classList.contains('hidden'));

    function showImage(index) {
        if (index < 0) index = itemsArray.length - 1;
        if (index >= itemsArray.length) index = 0;
        currentIndex = index;

        const currentItem = itemsArray[currentIndex];
        const img = currentItem.querySelector('img');
        const title = currentItem.querySelector('.gallery-item-title');
        
        lightboxImg.src = img.src;
        lightboxImg.alt = img.alt;
        lightboxCaption.innerText = title.innerText;
    }

    galleryItems.forEach(item => {
        item.addEventListener('click', () => {
            const currentVisibleItems = Array.from(galleryItems).filter(i => i.style.display !== 'none' && !i.classList.contains('hidden'));
            const idx = currentVisibleItems.indexOf(item);
            if (idx !== -1) {
                itemsArray.length = 0;
                itemsArray.push(...currentVisibleItems);
                
                lightbox.classList.add('active');
                showImage(idx);
            }
        });
    });

    lightboxClose.addEventListener('click', () => {
        lightbox.classList.remove('active');
    });

    lightbox.addEventListener('click', (e) => {
        if (e.target === lightbox) {
            lightbox.classList.remove('active');
        }
    });

    lightboxPrev.addEventListener('click', (e) => {
        e.stopPropagation();
        showImage(currentIndex - 1);
    });

    lightboxNext.addEventListener('click', (e) => {
        e.stopPropagation();
        showImage(currentIndex + 1);
    });

    document.addEventListener('keydown', (e) => {
        if (!lightbox.classList.contains('active')) return;
        if (e.key === 'Escape') lightbox.classList.remove('active');
        if (e.key === 'ArrowLeft') showImage(currentIndex - 1);
        if (e.key === 'ArrowRight') showImage(currentIndex + 1);
    });
}

