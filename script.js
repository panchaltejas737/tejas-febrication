// ===================== ANIMATED STAT COUNTERS =====================
(function initStatCounters() {
    const statBoxes = document.querySelectorAll('.stat-box');
    if (!statBoxes.length) return;

    function animateCounter(el) {
        const numEl = el.querySelector('.stat-num');
        if (!numEl || el.classList.contains('counted')) return;

        const rawText = numEl.textContent.trim();
        const suffix = rawText.replace(/[0-9]/g, ''); // e.g. '+', '%'
        const targetNum = parseInt(rawText.replace(/[^0-9]/g, ''), 10);

        if (isNaN(targetNum)) return;

        el.classList.add('counted');
        let start = 0;
        const duration = 1500;
        const startTime = performance.now();

        function tick(now) {
            const elapsed = now - startTime;
            const progress = Math.min(elapsed / duration, 1);
            // Easing: ease-out cubic
            const eased = 1 - Math.pow(1 - progress, 3);
            const current = Math.round(eased * targetNum);
            numEl.textContent = current + suffix;
            if (progress < 1) requestAnimationFrame(tick);
        }
        requestAnimationFrame(tick);
    }

    const statObserver = new IntersectionObserver((entries) => {
        entries.forEach(entry => {
            if (entry.isIntersecting) {
                animateCounter(entry.target);
                statObserver.unobserve(entry.target);
            }
        });
    }, { threshold: 0.5 });

    statBoxes.forEach(box => statObserver.observe(box));
})();

