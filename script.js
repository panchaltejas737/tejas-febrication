// Initialize Website
document.addEventListener('DOMContentLoaded', () => {
    // Check local storage for language preference
    const savedLang = localStorage.getItem('tejas_lang');
    if (savedLang && (savedLang === 'en' || savedLang === 'gu')) {
        currentLanguage = savedLang;
    } else {
        // Default to Gujarati if browser is set to Indian locale languages
        const userLocales = navigator.languages || [navigator.language];
        const isHindiOrGujarati = userLocales.some(l => l.startsWith('gu') || l.startsWith('hi') || l.startsWith('en-IN'));
        currentLanguage = isHindiOrGujarati ? 'gu' : 'en';
    }
    
    updateLanguageUI();
    updateTextTranslations();
    highlightActiveNav();
    setupActiveLinkObserver();
    initEstimator();
    initGalleryLightbox();
    initFAQAccordion();
    initEstimatorWizard();
    loadDynamicContent();
});

// Switch Language Logic
langToggleBtn.addEventListener('click', () => {
    currentLanguage = currentLanguage === 'en' ? 'gu' : 'en';
    localStorage.setItem('tejas_lang', currentLanguage);
    
    updateLanguageUI();
    updateTextTranslations();
    renderAllDynamic();
});

