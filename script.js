function calculateEstimate() {
    const categoryEl = document.getElementById('estCategory');
    const widthEl = document.getElementById('estWidth');
    const heightEl = document.getElementById('estHeight');
    const qualityEl = document.getElementById('estQuality');
    const resAreaEl = document.getElementById('resArea');
    const resPriceEl = document.getElementById('resPrice');

    if (!categoryEl || !widthEl || !heightEl || !qualityEl || !resAreaEl || !resPriceEl) return;

    const category = categoryEl.value;
    const width = parseFloat(widthEl.value) || 0;
    const height = parseFloat(heightEl.value) || 0;
    const quality = qualityEl.value;

    const area = width * height;
    const areaText = currentLanguage === 'gu' 
        ? `${area.toFixed(1)} ચો. ફૂટ` 
        : `${area.toFixed(1)} Sq. Ft.`;

    resAreaEl.innerText = areaText;

    if (area <= 0) {
        resPriceEl.innerText = "₹0";
        return;
    }

    const rateRange = pricingRates[category][quality];
    const minPrice = Math.round(area * rateRange[0]);
    const maxPrice = Math.round(area * rateRange[1]);

    resPriceEl.innerText = `₹${minPrice.toLocaleString('en-IN')} - ₹${maxPrice.toLocaleString('en-IN')}*`;
}

function saveEstimateToDatabase(message) {
    const name = prompt(currentLanguage === 'gu' ? 'કૃપા કરીને તમારું નામ દાખલ કરો:' : 'Please enter your name:');
    if (!name) return null;
    const phone = prompt(currentLanguage === 'gu' ? 'કૃપા કરીને તમારો ૧૦-આંકડાનો ફોન નંબર દાખલ કરો:' : 'Please enter your 10-digit phone number:');
    if (!phone) return null;
    
    // Clean phone number (remove spaces, hyphens, parentheses, and leading +91 or 0)
    let cleanedPhone = phone.replace(/[\s\-\(\)\+]/g, '');
    if (cleanedPhone.startsWith('91') && cleanedPhone.length > 10) {
        cleanedPhone = cleanedPhone.substring(2);
    } else if (cleanedPhone.startsWith('0') && cleanedPhone.length > 10) {
        cleanedPhone = cleanedPhone.substring(1);
    }
    
    // Validate phone number
    const phoneRegex = /^[0-9]{10}$/;
    if (!phoneRegex.test(cleanedPhone)) {
        alert(currentLanguage === 'gu' ? 'કૃપા કરીને સાચો ફોન નંબર દાખલ કરો.' : 'Please enter a valid phone number.');
        return null;
    }
    
    // Send to database in background (no await to prevent popup blocker)
    fetch('/api/enquiry', {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({ name, phone: cleanedPhone, message, source: 'estimator' })
    }).catch(() => {});
    
    return { name, phone: cleanedPhone };
}

